import json, math
m=json.load(open('model.json'))
L=[]
L.append('#pragma once\n// Melody statistics learned from the POP909 dataset (909 pop songs, melody tracks, MIT licence,\n// github.com/music-x-lab/POP909-Dataset): ~294k note-to-note moves measured in scale degrees.\n// Generated by train/gen_header.py. Do not edit by hand.\n\nnamespace melody::model\n{')
L.append('    // stepProb[mode][degree][metric][step + 7]: chance that the next note moves "step" scale steps,\n    // given the current scale degree (0-6) and where the next note falls (0 bar/half-bar, 1 beat, 2 8th, 3 16th).\n    // mode 0 = major, 1 = minor.')
L.append('    static const float stepProb[2][7][4][15] = {')
for mo in ('maj','min'):
    L.append('     {')
    for d in range(7):
        rows=[]
        for mc in range(4):
            t=m[mo]['trans'].get(f'{d}_{mc}',{})
            cnt=[t.get(str(s),0)+0.5 for s in range(-7,8)]
            tot=sum(cnt); rows.append('{'+','.join('%.4f'%(c/tot) for c in cnt)+'}')
        L.append('      {'+',\n       '.join(rows)+'},')
    L.append('     },')
L.append('    };')
for key,name in (('end','endProb'),('strong','strongProb'),('first','firstProb')):
    L.append(f'    static const float {name}[2][7] = {{')
    for mo in ('maj','min'):
        c=[m[mo][key].get(str(d),0)+0.5 for d in range(7)]; t=sum(c)
        L.append('        {'+','.join('%.4f'%(x/t) for x in c)+'},')
    L.append('    };')
rh=m['rhythms'][:48]
L.append('    // The most common one-bar rhythms (16 sixteenths, bit 0 = first 16th) and how often they appear.')
L.append('    static const unsigned short barRhythms[] = { '+', '.join(str(r[0]) for r in rh)+' };')
L.append('    static const int barRhythmCounts[] = { '+', '.join(str(r[1]) for r in rh)+' };')
L.append('    static const int numBarRhythms = %d;'%len(rh))
L.append('}')
open('/home/claude/repo/MelodyModel.h','w').write('\n'.join(L)+'\n')
